def get_hexagram_name(code: str) -> str:
    """根據 6-bit code 返回卦象名稱"""
    result = HEXAGRAM_NAMES.get(code)
    if result:
        symbol, name = result
        return f"{symbol} {name}"
    return "䷀ 未知"


def get_strategy_for_hexagram(code: str) -> str:
    """根據卦象返回對應執行策略（fallback 有意義）"""
    if code in STRATEGIES:
        return STRATEGIES[code]
    # Fallback — 根據卦象特徵推斷
    bits = list(code)
    yang_count = bits.count("1")
    if yang_count >= 5:
        return "通用 — 多陽爻，資源充足，可進取執行"
    elif yang_count <= 1:
        return "通用 — 多陰爻，建議收斂觀察，降低預期"
    elif "010" in code:
        return "通用 — 坎象出現，注意潛在風險，準備降級"
    else:
        return "通用降級 — 回到初爻重新規劃"
